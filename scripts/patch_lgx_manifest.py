#!/usr/bin/env python3
"""Merge curated metadata into an LGX archive's generated manifest.json.

The manifest generated by `lgx add` is authoritative for the fields that
describe package content: `hashes` (a Merkle tree over variants/ contents),
`manifestVersion` and `main` (the variant -> main-file mapping).  Replacing the
whole manifest with a hand-written one drops `hashes` and makes `lgx verify`
fail with "Missing content hashes in manifest".

This script therefore keeps those content-derived fields from the manifest
already in the archive and overlays only descriptive metadata (name, version,
description, type, category, author, icon, dependencies, ...).  Because it does
not touch any variant file bytes, the preserved hashes remain valid.

Usage: python3 scripts/patch_lgx_manifest.py <pkg.lgx> <manifest.json>
"""
import sys, tarfile, gzip, json, io


CONTENT_FIELDS = {"hashes", "manifestVersion", "main"}


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <pkg.lgx> <manifest.json>", file=sys.stderr)
        sys.exit(1)
    lgx_path, manifest_path = sys.argv[1], sys.argv[2]
    curated = json.load(open(manifest_path))

    with gzip.open(lgx_path, "rb") as gz:
        raw = gz.read()
    with tarfile.open(fileobj=io.BytesIO(raw)) as tf:
        members = [
            (m, tf.extractfile(m).read() if m.isfile() else None)
            for m in tf.getmembers()
        ]

    # Start from the manifest lgx generated so content hashes are preserved.
    generated = None
    for m, data in members:
        if m.name == "manifest.json" and data is not None:
            generated = json.loads(data)
            break
    if generated is None:
        print("Error: no manifest.json found in archive", file=sys.stderr)
        sys.exit(1)
    if not generated.get("hashes"):
        print("Error: generated manifest has no hashes", file=sys.stderr)
        sys.exit(1)

    merged = dict(generated)
    for key, value in curated.items():
        if key in CONTENT_FIELDS:
            continue
        merged[key] = value

    # Keep only `main` entries whose variant directory exists, then ensure every
    # real variant still has a main entry (from the generated mapping).
    archive_variants = {
        m.name.split("/")[1]
        for m, _ in members
        if m.name.startswith("variants/") and m.name.count("/") >= 1 and m.name.split("/")[1]
    }
    generated_main = generated.get("main", {})
    main = {k: v for k, v in generated_main.items() if k in archive_variants}
    for variant in archive_variants:
        if variant not in main and variant in generated_main:
            main[variant] = generated_main[variant]
    merged["main"] = main

    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", mtime=0) as gz_out:
        with tarfile.open(fileobj=gz_out, mode="w") as tf_out:
            mb = json.dumps(merged, indent=2, sort_keys=True).encode()
            info = tarfile.TarInfo("manifest.json")
            info.size = len(mb)
            info.mtime = info.uid = info.gid = 0
            info.mode = 0o644
            tf_out.addfile(info, io.BytesIO(mb))
            for m, data in members:
                if m.name == "manifest.json":
                    continue
                tf_out.addfile(m, io.BytesIO(data)) if data is not None else tf_out.addfile(m)

    with open(lgx_path, "wb") as f:
        f.write(buf.getvalue())
    print(f"Patched {lgx_path}: merged curated metadata, preserved generated hashes")
    print(f"  manifestVersion={merged['manifestVersion']} root={merged['hashes'].get('root')}")


if __name__ == "__main__":
    main()
